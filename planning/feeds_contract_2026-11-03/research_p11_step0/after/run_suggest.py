"""P11b L9: run the shipped Suggest (CLI `suggest --json`) over the step 0 row set.

Run (from any directory):

    python3 -I run_suggest.py [path/to/rs_cam_cli]

The default CLI is the release build of this checkout (`target/release/rs_cam_cli`).
The script writes, next to itself:

- `projects/<material>.toml`: one project per vendor material family; one tool and one
  Pocket toolpath per step 0 case (the case's target condition), and one per reference
  condition (the 1 x D row condition of group D, the reference row of group W);
- `suggest_raw.jsonl`: the CLI output, one JSON record per toolpath;
- `results.json`: the per-case Suggest chip, feed and band, and the pass rule applied.

Rules (fixed before the run; `../PREREGISTRATION.md`, "Pass rule"):

- The case set is the step 0 case set (`../results.json`, `cases`), unchanged.
- A case passes when the Suggest chip (shipped feed / (rpm x Z), the calculator point at
  the case's stated depth and width) lies inside the printed band of the target. The band
  of a group D case is the row band x 0.75 (2 x D) or x 0.50 (3 x D), as in step 0. A band
  with one printed value passes within +/- 5 % (`point_tol` of step 0).
- A family "reproduces the rows" at >= 80 % of its testable cases (step 0 `pass_fraction`).
  The verdict per group reads the same 80 %.
- The Garr finish case is run as a finish op (L2: a finish pass does not thin), the other
  cases as a roughing Pocket. The finish op is Drop Cutter with the case's stepover.

Assumptions, one statement each for all cases:

- Solid wood maps to the generic species of its family (`GenericHardwood`,
  `GenericSoftwood`); plywood to `HardwoodFaced` / `Softwood`; MDF, HDF and particleboard to
  their sheet kind; plastics to their family; aluminium to 6061-T6. Suggest may pick another
  vendor row than the case's row; the comparison is always against the case's printed band.
- The tool states its diameter and flute count from the row, a flute of 4 x D (so 3 x D is
  under the 0.8 x flute guard), a stickout of 5 x D and centre cutting. The machine is the
  project default (no `[job.machine]` block).
"""
import json
import os
import re
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
STEP0 = os.path.abspath(os.path.join(HERE, ".."))
REPO = os.path.abspath(os.path.join(HERE, "..", "..", "..", ".."))
CLI = sys.argv[1] if len(sys.argv) > 1 else os.path.join(REPO, "target", "release", "rs_cam_cli")

R0 = json.load(open(os.path.join(STEP0, "results.json")))
CONST = R0["constants"]
TOL = CONST["point_tol"]["value"]
PASS_FRACTION = CONST["pass_fraction"]["value"]

MATERIAL_TOML = {
    "hardwood": '[job.stock.material.SolidWood]\nspecies = "GenericHardwood"\n',
    "softwood": '[job.stock.material.SolidWood]\nspecies = "GenericSoftwood"\n',
    "plywood_hardwood": '[job.stock.material.Plywood]\ngrade = "HardwoodFaced"\n',
    "plywood_softwood": '[job.stock.material.Plywood]\ngrade = "Softwood"\n',
    "mdf": '[job.stock.material.SheetGood]\nkind = "Mdf"\n',
    "hdf": '[job.stock.material.SheetGood]\nkind = "Hdf"\n',
    "particleboard": '[job.stock.material.SheetGood]\nkind = "Particleboard"\n',
    "acrylic": '[job.stock.material.Plastic]\nfamily = "Acrylic"\n',
    "hdpe": '[job.stock.material.Plastic]\nfamily = "Hdpe"\n',
    "polycarbonate": '[job.stock.material.Plastic]\nfamily = "Polycarbonate"\n',
    "delrin": '[job.stock.material.Plastic]\nfamily = "Delrin"\n',
    "aluminum": '[job.stock.material.Aluminum]\nalloy = "Alloy6061T6"\n',
}


# The Pocket schema range of `depth_per_pass` (the CLI load refusal prints it: "finite,
# >= 0.1 and <= 50"). A case whose depth is above it cannot be stated on a Pocket; it is
# "not testable" and is counted as such.
POCKET_DPP_MAX_MM = 50.0


def is_finish(case):
    return case["group"] == "W" and "finish" in case["tgt_id"]


def conditions(case):
    """(role, ap, ae, finish) of each toolpath the case needs: the target, then the reference."""
    out = [("target", case["tgt_cond"]["ap"], case["tgt_cond"]["ae"], is_finish(case))]
    out.append(("reference", case["ref_cond"]["ap"], case["ref_cond"]["ae"], False))
    return out


def project_toml(material, entries):
    d_max = max(e["d"] for e in entries)
    lines = [
        "# P11b L9 (generated by run_suggest.py; do not edit by hand).",
        "format_version = 3",
        "",
        "[job]",
        f'name = "P11b after {material}"',
        "",
        "[job.stock]",
        f"x = {20 * d_max}",
        f"y = {20 * d_max}",
        f"z = {8 * d_max}",
        "origin_x = 0.0",
        "origin_y = 0.0",
        f"origin_z = {-8 * d_max}",
        "auto_from_model = false",
        "",
        MATERIAL_TOML[material],
        "[[models]]",
        "id = 0",
        'path = "square.svg"',
        'name = "Square"',
        'kind = "svg"',
        'units = { kind = "millimeters" }',
        "",
    ]
    for i, e in enumerate(entries):
        d, z = e["d"], e["z"]
        lines += [
            "[[tools]]",
            f"id = {i}",
            f'name = "T{i} D{d} Z{z}"',
            'type = "end_mill"',
            f"diameter = {d}",
            f"cutting_length = {{ stated = {4.0 * d} }}",
            f"stickout = {{ stated = {5.0 * d} }}",
            f"flute_count = {{ stated = {z} }}",
            f"tool_number = {i + 1}",
            'centre_cutting = { stated = "yes" }',
            "",
        ]
    lines += ["[[setups]]", 'name = "Setup 1"', ""]
    for i, e in enumerate(entries):
        lines += [
            "[[setups.toolpaths]]",
            f"id = {i}",
            f'name = "{e["key"]}"',
            "enabled = true",
            f"tool_id = {i}",
            "model_id = 0",
            'stock_source = "fresh"',
            "",
            "[setups.toolpaths.operation]",
        ]
        if e["finish"]:
            lines += [
                'kind = "drop_cutter"',
                "",
                "[setups.toolpaths.operation.params]",
                f"stepover = {e['ae']}",
                f"min_z = {-8 * d_max}",
                "slope_from = 0.0",
                "slope_to = 90.0",
                "",
            ]
        else:
            lines += [
                'kind = "pocket"',
                "",
                "[setups.toolpaths.operation.params]",
                f"stepover = {e['ae']}",
                f'floor = {{ from = "top", depth = {e["ap"]} }}',
                f"depth_per_pass = {e['ap']}",
                "climb = true",
                'pattern = "contour"',
                "angle = 0.0",
                "finishing_passes = 0",
                "",
            ]
    return "\n".join(lines) + "\n"


def in_band(x, lo, hi):
    if x is None:
        return None
    if lo is None or abs(hi - lo) < 1e-12:
        return abs(x - hi) <= TOL * hi
    return lo * (1 - 1e-9) <= x <= hi * (1 + 1e-9)


def main():
    cases = R0["cases"]
    by_material = {}
    for ci, case in enumerate(cases):
        for role, ap, ae, finish in conditions(case):
            if ap is None and not finish:
                continue
            if not finish and ap > POCKET_DPP_MAX_MM:
                continue
            key = f"c{ci}-{role}"
            by_material.setdefault(case["material"], []).append(
                dict(key=key, case=ci, role=role, d=case["d"], z=case["z"],
                     ap=ap if ap is not None else case["d"], ae=ae, finish=finish))
    os.makedirs(os.path.join(HERE, "projects"), exist_ok=True)
    # A square outline: the toolpaths need a model id; Suggest reads no geometry.
    with open(os.path.join(HERE, "projects", "square.svg"), "w") as f:
        f.write('<svg xmlns="http://www.w3.org/2000/svg" width="40mm" height="40mm" '
                'viewBox="0 0 40 40">\n  <rect x="5" y="5" width="30" height="30" fill="none" '
                'stroke="black" stroke-width="1" />\n</svg>\n')
    raw = {}
    with open(os.path.join(HERE, "suggest_raw.jsonl"), "w") as rawf:
        for material, entries in sorted(by_material.items()):
            path = os.path.join(HERE, "projects", f"{material}.toml")
            with open(path, "w") as f:
                f.write(project_toml(material, entries))
            out = subprocess.run([CLI, "suggest", "--json", path], capture_output=True, text=True,
                                 check=True).stdout
            for line in out.splitlines():
                rec = json.loads(line)
                rec["_material"] = material
                # Keep the calculator block, the tool, the error and the envelope placement;
                # the limits, the speeds grid and the bases are large and are not read here.
                prof = rec.get("profile")
                if isinstance(prof, dict):
                    env = prof.get("envelope")
                    rec["profile"] = dict(
                        calculator=prof.get("calculator"),
                        envelope=(dict(operator=env.get("operator"),
                                       proposal_binding=env.get("proposal_binding"))
                                  if isinstance(env, dict) and "boundary" in env else env))
                rawf.write(json.dumps(rec, separators=(",", ":")) + "\n")
                raw[rec["toolpath_name"]] = rec

    def read(key):
        rec = raw.get(key)
        if rec is None or "profile" not in rec or "calculator" not in rec["profile"]:
            return dict(error=(rec or {}).get("error", "no record"))
        c = rec["profile"]["calculator"]
        z = rec["tool"]["flute_count"]
        chip = c["feed_rate_mm_min"] / (c["rpm"] * z) if c["rpm"] > 0 else None
        w = c["warnings"]
        ceiling = None
        for text in w:
            m = re.search(r"feed_ceiling_mm_min: ([0-9.]+)", text)
            if m:
                ceiling = float(m.group(1))
        return dict(available_kw=c["available_power_kw"], feed_ceiling=ceiling,chip=chip, feed=c["feed_rate_mm_min"], rpm=c["rpm"], target_chip=c["chip_load_mm"],
                    ap=c["axial_depth_mm"], ae=c["radial_width_mm"], row=c["vendor_source"],
                    feed_capped=any(s.startswith("FeedRateClamped") for s in w),
                    rpm_lowered=any(s.startswith("RpmLoweredForFeedCeiling") for s in w),
                    power_limited=c["power_limited"],
                    rubbing=any(s.startswith("ChiploadBelowRubbingFloor") for s in w))

    out_cases = []
    for ci, case in enumerate(cases):
        lo, hi = case["tgt_band"]
        tgt = read(f"c{ci}-target")
        ref = read(f"c{ci}-reference") if case["ref_cond"]["ap"] is not None else dict(error="no ap")
        ref_band = None
        if case["group"] == "D":
            # The reference band is the row's own printed band at 1 x D (the target band / scale).
            scale = 0.75 if case["k"] == 2 else 0.50
            ref_band = [None if lo is None else lo / scale, hi / scale]
        out_cases.append(dict(
            group=case["group"], label=case["label"], id=case["id"], tgt_id=case["tgt_id"],
            vendor=case["vendor"], material=case["material"], k=case.get("k"), d=case["d"], z=case["z"],
            tgt_cond=case["tgt_cond"], ref_cond=case["ref_cond"], tgt_band=[lo, hi], fz1=case["fz1"],
            step0_I1=case["pred"]["I1"], suggest=tgt, reference=ref, ref_band=ref_band,
            passes=in_band(tgt.get("chip"), lo, hi),
            ref_in_band=(None if ref_band is None else in_band(ref.get("chip"), *ref_band)),
            ratio_to_band_mid=(None if tgt.get("chip") is None else
                               tgt["chip"] / (hi if lo is None else (lo + hi) / 2)),
            ref_ratio_to_band_mid=(None if ref_band is None or ref.get("chip") is None else
                                   ref["chip"] / (ref_band[1] if ref_band[0] is None
                                                  else (ref_band[0] + ref_band[1]) / 2))))

    def frac(sub, field="passes"):
        vals = [c[field] for c in sub if c[field] is not None]
        return dict(n=len(vals), passed=sum(vals), frac=(sum(vals) / len(vals) if vals else None))

    families = {}
    for c in out_cases:
        families.setdefault(f'{c["group"]}:{c["vendor"]}', []).append(c)
    def median(xs):
        xs = sorted(x for x in xs if x is not None)
        if not xs:
            return None
        m = len(xs) // 2
        return xs[m] if len(xs) % 2 else (xs[m - 1] + xs[m]) / 2

    def unbound(c):
        s = c["suggest"]
        return not (s.get("feed_capped") or s.get("rpm_lowered") or s.get("power_limited"))

    per_family = {k: dict(target=frac(v), reference=frac(v, "ref_in_band"),
                          target_unbound=frac([c for c in v if unbound(c)]),
                          median_ratio_target=median(c["ratio_to_band_mid"] for c in v),
                          median_ratio_reference=median(c["ref_ratio_to_band_mid"] for c in v),
                          feed_capped=sum(1 for c in v if c["suggest"].get("feed_capped")),
                          rpm_lowered=sum(1 for c in v if c["suggest"].get("rpm_lowered")),
                          power_limited=sum(1 for c in v if c["suggest"].get("power_limited")),
                          errors=sum(1 for c in v if "error" in c["suggest"]))
                  for k, v in sorted(families.items())}
    groups = {g: frac([c for c in out_cases if c["group"] == g]) for g in ("W", "D")}
    verdict = ("PASS" if all(groups[g]["frac"] is not None and groups[g]["frac"] >= PASS_FRACTION
                             for g in groups) else "FAIL")
    machine = dict(
        available_kw=sorted({c["suggest"]["available_kw"] for c in out_cases
                             if c["suggest"].get("available_kw") is not None}),
        feed_ceiling_mm_min=sorted({c["suggest"]["feed_ceiling"] for c in out_cases
                                    if c["suggest"].get("feed_ceiling") is not None}))
    res = dict(cli=CLI, machine=machine, tol=TOL, pass_fraction=PASS_FRACTION, n_cases=len(out_cases),
               groups=groups, per_family=per_family, verdict=verdict, cases=out_cases)
    json.dump(res, open(os.path.join(HERE, "results.json"), "w"), indent=1)
    print("verdict", verdict)
    for g, v in groups.items():
        print(g, v)
    for k, v in per_family.items():
        print(k, v)


if __name__ == "__main__":
    main()
